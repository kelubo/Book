def load():
    raw = io.open(P, "rb").read()
    text = raw.decode("utf-8")
    nl = "\r\n" if "\r\n" in text[:4000] else "\n"
    return text.split(nl), nl, text.endswith(nl)


def save(lines, nl, tail):
    io.open(P, "w", encoding="utf-8", newline="").write(nl.join(lines) + (nl if tail else ""))


def uniq(lines, pred, what, lo=0, hi=None):
    hi = len(lines) if hi is None else hi
    hits = [i for i in range(lo, hi) if pred(lines[i])]
    assert len(hits) == 1, "定位失败【%s】：命中 %d 处" % (what, len(hits))
    return hits[0]


