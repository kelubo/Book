# 载入三卷正文（剔注释行）
data = {}
for fn in FILES:
    lines = load(fn)
    body = []
    chaps = []
    cur = "(卷首)"
    for i, ln in enumerate(lines, 1):
        s = ln.strip()
        if s.startswith("%"):
            continue
        m = re.match(r"\\chapter\{([^{}]*)\}", s)
        if m:
            cur = m.group(1).strip()
            chaps.append((i, cur))
        body.append((i, s, cur))
    data[fn] = dict(lines=lines, body=body, chaps=chaps)

out = []
out.append("== 词面矩阵（三卷命中行数；剔注释） ==")
out.append("分类 | 主题 | book | female | male | 定位章（book 命中最多的章）")
gaps = []
for cat, label, kws in TOPICS:
    kwl = [k for k in kws.split("|") if k]
    cnt = {}
    chapcnt = {}
    for fn in FILES:
        c = 0
        for i, s, cur in data[fn]["body"]:
            if any(k in s for k in kwl):
                c += 1
                chapcnt[cur] = chapcnt.get(cur, 0) + 1
        cnt[fn] = c
    tot = sum(cnt.values())
    top_ch = ""
    if chapcnt:
        top_ch = sorted(chapcnt.items(), key=lambda x: -x[1])[:2]
        top_ch = "；".join("%s(%d)" % (a, b) for a, b in top_ch)
    line = "%s | %s | %d | %d | %d | %s" % (cat, label, cnt["book.tex"], cnt["female.tex"], cnt["male.tex"], top_ch)
    out.append(line)
    if tot <= 3:
        gaps.append((tot, label, cnt["book.tex"], cnt["female.tex"], cnt["male.tex"]))

out.append("")
out.append("== 缺口候选（总命中 <= 3 行，按命中升序） ==")
for tot, label, a, b, c in sorted(gaps):
    out.append("  %-24s total=%-3d (book %d / female %d / male %d)" % (label, tot, a, b, c))

out.append("")
out.append("== 章节数分布（各卷章列表，含节数） ==")
for fn in FILES:
    ch = data[fn]["chaps"]
    lines = data[fn]["lines"]
    # 统计每 chapter 下 section 数
    secs = []
    for i, ln in enumerate(lines, 1):
        s = ln.strip()
        if s.startswith("%"):
            continue
        m = re.match(r"\\section\{", s)
        if m:
            secs.append(i)
    out.append("--- %s: %d 章 / %d 节 ---" % (fn, len(ch), len(secs)))
    for idx, (ln_no, t) in enumerate(ch):
        end = ch[idx + 1][0] if idx + 1 < len(ch) else len(lines)
        nsec = sum(1 for x in secs if ln_no < x < end)
        out.append("  L%-6d %-46s 节数=%d 行长=%d" % (ln_no, t[:44], nsec, end - ln_no))

out.append("")
out.append("== 浅小节（section/subsection 正文非空行 < 5） ==")
shallow = []
for fn in FILES:
    lines = data[fn]["lines"]
    marks = []
    for i, ln in enumerate(lines, 1):
        s = ln.strip()
        if s.startswith("%"):
            continue
        m = re.match(r"\\(section|subsection)\{([^{}]*)\}", s)
        if m:
            marks.append((i, m.group(1), m.group(2).strip()))
    for idx, (ln_no, lv, t) in enumerate(marks):
        # 找下一个同级或更高级标题
        end = None
        for j in range(idx + 1, len(marks)):
            jl, jlv = marks[j][1], None
            if marks[j][1] == "section" or (lv == "subsection" and marks[j][1] == "subsection"):
                end = marks[j][0]
                break
        if end is None:
            end = len(lines)
        body_n = sum(1 for x in lines[ln_no:end - 1] if x.strip() and not x.strip().startswith("%"))
        if body_n < 5:
            shallow.append((fn, ln_no, lv, t, body_n))
out.append("浅小节总数: %d" % len(shallow))
for fn, ln_no, lv, t, b in shallow[:120]:
    out.append("  %s L%-6d [%s] %-40s 正文=%d 行" % (fn, ln_no, lv, t[:38], b))

