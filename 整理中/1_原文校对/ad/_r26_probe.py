def strip_comments(s):
    # 逐行剔除 % 注释（\% 转义除外）
    out = []
    for ln in s.split('\n'):
        ln2 = re.sub(r'(?<!\\)%.*', '', ln)
        out.append(ln2)
    return '\n'.join(out)

